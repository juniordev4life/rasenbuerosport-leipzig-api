/**
 * The 64 trophies the office-foosball league tracks. Static metadata
 * versioned with the code — adding / changing a trophy is a code
 * change, not a DB write, so the league agrees on the shape of the
 * achievement system at deploy time.
 *
 * Each trophy carries a `conditionKey` that resolves to a function in
 * `src/api/services/trophyConditions.services.js`. The runtime calls
 * that function with `{ player, match, context, params }` and the
 * function returns a boolean. See the conditions module for the
 * full registry.
 *
 * Categories follow the design's color buckets:
 *
 *   win       — total-wins ladder + special win shapes
 *   streak    — consecutive-win shapes
 *   goal      — goals + assists ladders + per-match scoring shapes
 *   defense   — clean sheets, comfortable wins
 *   special   — marker-driven shapes (comebacks, late winners, shootout)
 *   duo       — bound to a player pair (scope: "duo")
 *   rivalry   — H2H-driven shapes
 *   meta      — engagement + peak-ELO milestones
 *   hidden    — uncommon situations, masked until unlocked
 *
 * Rarity nudges the trophy room's visual weight; `hidden: true` means
 * the API masks name + description until the player unlocks it.
 *
 * @typedef {Object} TrophyDefinition
 * @property {string} id - Stable short ID (e.g. "S1", "T14"). Survives renames.
 * @property {'win'|'streak'|'goal'|'defense'|'special'|'duo'|'rivalry'|'meta'|'hidden'} category
 * @property {string} name - Display name (German).
 * @property {string} description - Display description (German).
 * @property {'bronze'|'silver'|'gold'|'diamond'} rarity
 * @property {boolean} hidden - Masked in the UI until unlocked.
 * @property {'individual'|'duo'} scope - Per-player or per-pair tracking.
 * @property {string} conditionKey - Lookup key into trophyConditions.
 * @property {Object} conditionParams - Threshold / params for the condition.
 */

